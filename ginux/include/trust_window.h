#ifndef TRUST_WINDOW_H
#define TRUST_WINDOW_H

#include <stdint.h>

/* trust_window.h -- نافذة الأمانة (كتاب الفلسفة: "الاستخلاف"، الفصل
 * السادس والسابع) -- ثالث تطبيق فلسفي حقيقي في الكود.
 *
 * الفكرة: أي عملية "لا رجعة فيها" (حاليًا: unlink فقط -- initrd أول
 * مكان عندنا فيه فعل حذف حقيقي) لا تُنفَّذ فورًا. تدخل نافذة تأخير
 * قابلة للإلغاء (بضع ثوانٍ)، بصرف النظر عن صلاحية الطالب -- حتى أعلى
 * صلاحية في النظام تمر من نفس النافذة، بدون استثناء (انظر كتاب الفلسفة،
 * الفصل السابع: "لا سلطة مطلقة").
 *
 * الفرق عن "تأكيد" (Are you sure? Y/N) عادي:
 *   1. لا يعتمد على انتباه المستخدم اللحظي -- فاصل زمني حقيقي، وليس
 *      ضغطة زر واحدة.
 *   2. مبني في مستوى استدعاء النظام (syscall) نفسه، وليس تطبيقًا طرفيًا
 *      قابل للتجاوز.
 *   3. لا يوجد استثناء لأي صلاحية -- انظر process_execve/fork، لا يوجد
 *      "خط سريع" لأي process.
 *
 * التنفيذ الفعلي بعد انتهاء النافذة يحدث من trust_window_tick()،
 * تُستدعى من pit_callback (كل IRQ0 tick) -- بعيدة عمدًا عن أي قفل
 * الخاص بـ schedule()/process.c، حتى لا تزيد مخاطرة البق الرابع المعروف
 * (استقرار الـ scheduler، انظر HANDOFF.md §5). */

#define TRUST_WINDOW_MAX_PENDING 64  /* كان 16: برامج مثل المترجم تحذف عشرات الملفات المؤقتة */

/* مدة النافذة بوحدة PIT ticks (100Hz افتراضيًا) -- 300 tick = 3 ثوانٍ
   تقريبًا. قيمة قصيرة نسبيًا لسهولة الاختبار؛ في نظام حقيقي يمكن أن تكون
   أطول (دقائق) حسب خطورة العملية -- انظر كتاب الفلسفة، الفصل السادس:
   "اعتراض متوقع: أليس هذا بطئا غير ضروري؟". */
#define TRUST_WINDOW_TICKS 300

typedef enum {
    PENDING_DELETE_INITRD_UNLINK = 1,
} pending_op_type_t;

void trust_window_init(void);

/* تطلب حذف initrd file (بعد النافذة، وليس فورًا). ترجع handle >= 0
   (يُستعمل للإلغاء لاحقًا عبر trust_window_cancel)، أو -1 عند الفشل
   (الجدول ممتلئ، أو الملف غير موجود أصلًا). */
int trust_window_request_delete(const char* path, uint32_t requesting_pid);

/* تلغي طلب حذف معلّقًا -- يجب أن يكون pid نفسه الذي طلب الحذف (ليس أي
   process تستطيع إلغاء طلب process أخرى -- كل عملية مسؤولة عن قراراتها
   هي، لا عن قرارات الآخرين). ترجع 0 عند النجاح، -1 إذا كان handle
   غير صالح، أو غير معلّق، أو pid ليس نفسه. */
int trust_window_cancel(int handle, uint32_t requesting_pid);

/* تفحص كل الطلبات المعلقة، وتنفذ أي طلب انتهت نافذته. تُستدعى من
   pit_callback كل tick -- خفيفة (مسح مصفوفة صغيرة)، بدون قفل مع
   process.c. */
void trust_window_tick(uint32_t current_tick);

/* عدد الطلبات المعلقة حاليًا -- مفيدة للاختبار/المراقبة */
int trust_window_pending_count(void);

/* تلغي أي طلب حذف معلّق على هذا المسار. تُستدعى عندما يُعاد إنشاء الاسم (open بـ O_CREAT/O_TRUNC)
   بعد unlink: النمط المعتاد (ld وغيره: unlink ثم create بنفس الاسم) كان سيجعل نافذة الأمانة
   تحذف الملف *الجديد* بعد 3 ثوانٍ. إعادة الإنشاء قرار جديد يُلغي قرار الحذف القديم.
   ترجع عدد الطلبات الملغاة. */
int trust_window_cancel_path(const char* path);

#endif
